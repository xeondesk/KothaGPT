def _record(task: str, record_id: str, **fields) -> dict:
    record = {"task": task, "record_id": record_id, "split": _split(record_id)}
    record.update(fields)
    return record


def build_qa() -> list[dict]:
    records: list[dict] = []
    for pi, passage in enumerate(QA_PASSAGES):
        for qi, (question, answer) in enumerate(passage["facts"]):
            assert answer in passage["paragraph"], f"answer not a span: {answer!r}"
            for vi, prompt in enumerate(_QA_PROMPTS):
                record_id = f"qa:{pi}:{qi}:{vi}"
                records.append(
                    _record(
                        "bangla_qa",
                        record_id,
                        prompt=prompt.format(q=question),
                        passage=passage["paragraph"],
                        reference=answer,
                        title=passage["title"],
                    )
                )
    return records


def build_translation() -> list[dict]:
    records: list[dict] = []
    # entity expansions of the templated pool (both directions)
    for ti, (bn_t, en_t) in enumerate(_TRANSLATION_TEMPLATES):
        for ei, (bn_e, en_e) in enumerate(_ENTITIES):
            bn = bn_t.format(E=bn_e)
            en = en_t.format(E=en_e)
            record_id = f"trans:{ti}:{ei}:bn2en"
            records.append(
                _record(
                    "bangla_translation",
                    record_id,
                    source_text=bn,
                    reference=en,
                    source_lang="bn",
                    target_lang="en",
                )
            )
            record_id = f"trans:{ti}:{ei}:en2bn"
            records.append(
                _record(
                    "bangla_translation",
                    record_id,
                    source_text=en,
                    reference=bn,
                    source_lang="en",
                    target_lang="bn",
                )
            )
    # hand-curated extra pairs (both directions)
    for ei, (bn, en) in enumerate(_EXTRA_PAIRS):
        records.append(
            _record(
                "bangla_translation",
                f"trans:x:{ei}:bn2en",
                source_text=bn,
                reference=en,
                source_lang="bn",
                target_lang="en",
            )
        )
        records.append(
            _record(
                "bangla_translation",
                f"trans:x:{ei}:en2bn",
                source_text=en,
                reference=bn,
                source_lang="en",
                target_lang="bn",
            )
        )
    return records


def build_summarization() -> list[dict]:
    records: list[dict] = []
    for ai, (article, summary) in enumerate(SUMMARIES):
        for vi, prompt in enumerate(_SUMMARY_PROMPTS):
            record_id = f"sum:{ai}:{vi}"
            records.append(
                _record(
                    "bangla_summarization",
                    record_id,
                    prompt=prompt.format(article=article),
                    source=article,
                    reference=summary,
                )
            )
    return records


def build_generation() -> list[dict]:
    records: list[dict] = []
    for gi, (prompt, reference) in enumerate(_GENERATION):
        record_id = f"gen:{gi}"
        records.append(
            _record(
                "bangla_generation",
                record_id,
                prompt=prompt,
                reference=reference,
            )
        )
    return records


_BUILDERS = {
    "bangla_qa": (build_qa, 576),
    "bangla_translation": (build_translation, 1110),
    "bangla_summarization": (build_summarization, 104),
    "bangla_generation": (build_generation, 26),
}


def generate(out_dir: Path | None = None) -> dict[str, list[dict]]:
    """Build every task dataset, asserting the plan's minimum counts."""
    out_dir = Path(out_dir or _OUT_DIR)
    datasets: dict[str, list[dict]] = {}
    manifest: dict[str, dict] = {"name": "bangla", "version": "v1", "tasks": {}}
    for task, (builder, minimum) in _BUILDERS.items():
        records = builder()
        assert len(records) >= minimum, f"{task}: {len(records)} < {minimum}"
        datasets[task] = records
        counts: dict[str, int] = {"total": len(records)}
        for split in ("dev", "test"):
            counts[split] = sum(1 for r in records if r["split"] == split)
        manifest["tasks"][task] = counts
        print(f"{task}: {len(records)} records ({counts['dev']} dev / {counts['test']} test)")

    out_dir.mkdir(parents=True, exist_ok=True)
    for task, records in datasets.items():
        path = out_dir / f"{task}.jsonl"
        with path.open("w", encoding="utf-8") as fh:
            for record in records:
                fh.write(json.dumps(record, ensure_ascii=False) + "\n")
    (out_dir / "MANIFEST.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return datasets


if __name__ == "__main__":
    generate()
